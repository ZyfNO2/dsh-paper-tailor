/** Generate/verify the self-contained trusted report runtime; no runtime CDN or Host. */
import { execFileSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';
import * as os from 'node:os';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'packages/evolver-ui/src/client/general/report-core/offline-runtime.generated.ts');
let binary = process.env.ESBUILD_BIN;
if (!binary) {
  // Resolve the esbuild binary from THIS tree's install. No developer-store
  // fallback: a machine-local path satisfying the build is exactly what a
  // reproducible release must not depend on.
  const platformPackages = ['@esbuild/win32-x64', '@esbuild/linux-x64', '@esbuild/darwin-arm64', '@esbuild/darwin-x64'];
  for (const platformPackage of platformPackages) {
    const binName = platformPackage.includes('win32') ? 'esbuild.exe' : path.join('bin', 'esbuild');
    const candidate = path.join(root, 'node_modules', platformPackage, binName);
    if (fs.existsSync(candidate)) { binary = candidate; break; }
  }
}
if (!binary) throw new Error('No esbuild binary in this tree; run `npm install` at the repository root or set ESBUILD_BIN');
const staging = fs.mkdtempSync(path.join(os.tmpdir(), 'dsh-offline-runtime-'));
try {
  const output = path.join(staging, 'runtime.js');
  execFileSync(binary, [path.join(root, 'packages/evolver-ui/src/client/general/report-core/offline-entry.tsx'), '--bundle', '--platform=browser', '--format=iife', '--jsx=automatic', '--target=es2022', '--minify', '--legal-comments=none', '--define:process.env.NODE_ENV="production"', `--outfile=${output}`], { stdio: 'inherit', cwd: root });
  const script = fs.readFileSync(output, 'utf8').trimEnd();
  if (/<\/script/i.test(script) || /\bimport\s*\(/.test(script) || /\brequire\s*\(/.test(script)) throw new Error('Offline runtime contains HTML closing tag or unresolved module dependency');
  const digest = createHash('sha256').update(script).digest('base64');
  const require = createRequire(path.join(root, 'package.json'));
  const licenses = ['react', 'react-dom'].map(name => `${name}\n${fs.readFileSync(path.join(path.dirname(require.resolve(`${name}/package.json`)), 'LICENSE'), 'utf8')}`).join('\n\n');
  const source = `// Generated by scripts/build-report-offline-runtime.ts --write; do not hand-edit.\nexport const OFFLINE_REPORT_RUNTIME = ${JSON.stringify(script)};\nexport const OFFLINE_REPORT_CSP_HASH = ${JSON.stringify(`sha256-${digest}`)};\nexport const OFFLINE_REPORT_LICENSES = ${JSON.stringify(licenses)};\n`;
  if (process.argv.includes('--write')) fs.writeFileSync(target, source);
  else if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== source) throw new Error('Offline runtime stale/missing; run node --experimental-strip-types scripts/build-report-offline-runtime.ts --write');
  console.log(`PASS trusted offline runtime ${process.argv.includes('--write') ? 'generated' : 'matches current source'} (${Buffer.byteLength(script)} bytes)`);
} finally { fs.rmSync(staging, { recursive: true, force: true }); }
